'''

--------Membership Operators-----------

--> Membership operators are also returns two condition either true or false 
--> If the condition is true returns TRUE
--> If the condition is false returns FALSE
 
Types:

1.in
2.not in


'''


word=str(input("enter the word:"))
character=str(input("enter the character:"))

print(character in word)

a="apple"
print("z" in a)
print("z" not in a)

b="welcome to the class"
print("class" in b)

c="welcome to the class"
print(" " in c)
print(" " not in c)






































