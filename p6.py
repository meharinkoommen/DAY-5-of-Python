'''

--------Identity Operators-----------

--> Identity operators are also returns two condition either true or false 
--> If the condition is true returns TRUE
--> If the condition is false returns FALSE
 
Types:

1.is
2. is not

'''

word1=str(input("enter the word1:"))
word2=str(input("enter the word2"))

print(word1 is word2)
print(word1 == word2)
print(word1 is not word2)